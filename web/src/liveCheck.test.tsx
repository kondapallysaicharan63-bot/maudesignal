// -0 and +0 are the same number for this comparison (Python prints -0.0 for a rounded tiny negative).
const same = (a: unknown, b: unknown) => {
  const z = (v: unknown): unknown => {
    if (typeof v === 'number') return v + 0
    if (Array.isArray(v)) return v.map(z)
    if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, z(x)]))
    return v
  }
  expect(z(a)).toEqual(z(b))
}

describe('parity with maudesignal.monitor.live_check (fixtures generated by Python)', () => {
  it('has at least 200 classification cases', () => {
    expect(parity.classify.length).toBeGreaterThanOrEqual(200)
  })

  it('classify_counts: every case gives the same classification and figures', () => {
    let flagged = 0
    for (const c of parity.classify) {
      const counts = c.counts as unknown as WindowCounts
      const got = classifyCounts(c.code, counts, buildWindow(c.as_of))
      same(got, c.expected)
      if (got.classification !== 'stable') flagged++
    }
    // The fixtures exercise every rule, not only "no change".
    const kinds = new Set(parity.classify.flatMap((c) => c.expected.triggers))
    expect([...kinds].sort()).toEqual(['new_signal', 'severity_escalation', 'spike'])
    expect(flagged).toBeGreaterThan(100)
  })

  it('_norm: event-type normalisation', () => {
    for (const c of parity.norm) {
      expect(normalizeTypes(c.rows as [string, number][], c.total)).toEqual(c.expected)
    }
  })

  it('build_window: dates, including a leap day', () => {
    for (const c of parity.windows) expect(buildWindow(c.as_of)).toEqual(c.expected)
  })

  it('verify_url: same openFDA links', () => {
    for (const c of parity.urls) {
      const [code, start, end, count] = c.args as [string, string | null, string | null, string | null]
      expect(verifyUrl(code, start, end, count ?? undefined)).toBe(c.expected)
    }
  })
})

describe('the stored sweep rows (computed by the Python code against openFDA)', () => {
  const rows = sweep.rows.filter((r) => r.classification !== 'stable')
  it('has flagged rows to compare with', () => expect(rows.length).toBeGreaterThan(0))

  it('windows and figures re-derive from each row', () => {
    for (const r of sweep.rows) {
      expect(buildWindow(r.window.as_of)).toEqual({
        as_of: r.window.as_of,
        current_start: r.window.current_start,
        current_end: r.window.current_end,
        baseline_start: r.window.baseline_start,
        baseline_end: r.window.baseline_end,
      })
      expect(r.baseline_count / 4).toBe(r.baseline_weekly_mean)
      if (r.baseline_count) expect(roundHalfEven((r.current_count * 4) / r.baseline_count, 2)).toBe(r.spike_ratio)
    }
  })

  it('query links equal the stored ones for the same windows', () => {
    for (const r of rows) {
      const w = r.window
      const want = new Map(r.queries.map(([label, url]) => [label, url]))
      const code = r.product_code
      const before = addDays(w.current_start, -1)
      expect(verifyUrl(code, w.current_start, w.current_end, 'event_type.exact')).toBe(want.get('This week, by event type'))
      expect(verifyUrl(code, w.baseline_start, w.baseline_end, 'event_type.exact')).toBe(want.get('4 weeks before, by event type'))
      expect(verifyUrl(code, '19900101', before)).toBe(want.get('Everything before this week'))
      expect(verifyUrl(code, '19900101', before, 'event_type.exact')).toBe(want.get('Everything before this week, by event type'))
    }
  })
})

describe('rounding and codes', () => {
  it('rounds exact ties to even like Python and everything else to nearest', () => {
    expect(roundHalfEven(0.125, 2)).toBe(0.12)
    expect(roundHalfEven(0.375, 2)).toBe(0.38)
    expect(roundHalfEven(2.5, 0)).toBe(2)
    expect(roundHalfEven(1.005, 2)).toBe(1) // the double is slightly below 1.005
    expect(roundHalfEven(14.285714285714285, 2)).toBe(14.29)
    expect(roundHalfEven(-0.125, 2)).toBe(-0.12)
  })

  it('validates a product code', () => {
    expect(normalizeCode(' llz ')).toBe('LLZ')
    expect(normalizeCode('LL')).toBeNull()
    expect(normalizeCode('L1Z')).toBeNull()
  })
})

// ── the MaudeSignal API (mocked fetch) ───────────────────────────────────────
const BASE = 'https://api.example.test'
const json = (body: unknown, status = 200) => Promise.resolve(new Response(JSON.stringify(body), { status }))

/** What the API sends for LLZ: LiveCheck.to_dict() under "check" (test fixture, not real data). */
const CHECK = {
  product_code: 'LLZ',
  as_of: '20260930',
  window: buildWindow('20260930'),
  classification: 'spike',
  change: 'reports suddenly increased',
  triggers: ['spike'],
  current_count: 12,
  current_severe_count: 1,
  current_severe_share: 0.0833,
  baseline_count: 4,
  baseline_weekly_mean: 1,
  baseline_severe_count: 0,
  baseline_severe_share: 0,
  severe_share_delta_pp: 8.33,
  spike_ratio: 12,
  prior_report_count: 44,
  new_event_types: [],
  current_event_type_counts: [['malfunction', 11], ['injury', 1]],
  queries: [
    ['This week, by event type', 'https://example.test/q1'],
    ['Everything before this week', 'https://example.test/q2'],
  ],
}
const ANSWER = { speakable: 'x', facts: [], advisory: 'Advisory text for a person to review.', provenance: 'p', check: CHECK }

const memStore = (): KeyStore => {
  const data = new Map<string, string>()
  return { getItem: (k) => data.get(k) ?? null, setItem: (k, v) => void data.set(k, v) }
}
const now = Date.UTC(2026, 9, 29, 8)
const html = (out: Awaited<ReturnType<typeof checkDevice>>) => renderToStaticMarkup(<OutcomeView out={out} />)

describe('apiBaseFrom', () => {
  it('drops a trailing slash and refuses an unset or non-URL value', () => {
    expect(apiBaseFrom('https://a.test/')).toBe('https://a.test')
    expect(apiBaseFrom('https://a.test///')).toBe('https://a.test')
    expect(apiBaseFrom(undefined)).toBeNull()
    expect(apiBaseFrom('')).toBeNull()
    expect(apiBaseFrom('not a url')).toBeNull()
    expect(apiUrl('https://a.test', 'LLZ')).toBe('https://a.test/v1/public/check_device_type?product_code=LLZ')
  })
})

describe('checkDevice against the MaudeSignal API', () => {
  beforeEach(() => resetLiveCheckMemory())

  it('success: one GET to our API, figures and openFDA links come from "check"', async () => {
    const calls: string[] = []
    const fetcher = vi.fn((u: string) => {
      calls.push(u)
      return json(ANSWER)
    })
    const out = await checkDevice('llz', { fetcher, apiBase: BASE, session: memStore(), local: memStore(), now })
    expect(calls).toEqual([`${BASE}/v1/public/check_device_type?product_code=LLZ`])
    expect(out.ok && out.used === 1 && !out.cached).toBe(true)
    const page = html(out)
    expect(page).toContain('Reports suddenly increased') // label from "change"
    expect(page).toContain('12.00×') // spike_ratio from "check"
    expect(page).toContain('>12<') // current_count
    expect(page).toContain('1.00') // baseline_weekly_mean
    expect(page).toContain('href="https://example.test/q1"')
    expect(page).toContain('href="https://example.test/q2"')
    expect(page).toContain('12 reports this week against a weekly mean of 1.00')
    expect(page).toContain('Advisory text for a person to review.')
    expect(page).toContain('2026-09-24') // window from "check"
  })

  it('no request ever goes to openFDA', async () => {
    const calls: string[] = []
    await checkDevice('LLZ', {
      fetcher: (u) => {
        calls.push(u)
        return json(ANSWER)
      },
      apiBase: BASE,
      session: memStore(),
      local: memStore(),
      now,
    })
    expect(calls.every((c) => c.startsWith(BASE))).toBe(true)
    expect(calls.some((c) => c.includes('api.fda.gov'))).toBe(false)
  })

  it('429 shows the fallback with the Streamlit link and no result', async () => {
    const out = await checkDevice('LLZ', { fetcher: () => json({}, 429), apiBase: BASE, session: memStore(), local: memStore(), now })
    expect(!out.ok && out.kind === 'rate').toBe(true)
    const page = html(out)
    expect(page).toContain('rate limited')
    expect(page).toContain(`href="${STREAMLIT_URL}"`)
    expect(page).toContain('No result is shown')
    expect(page).not.toContain('This week')
  })

  it('a network error shows the fallback', async () => {
    const out = await checkDevice('LLZ', {
      fetcher: () => Promise.reject(new TypeError('Failed to fetch')),
      apiBase: BASE,
      session: memStore(),
      local: memStore(),
      now,
    })
    expect(!out.ok && out.kind === 'network').toBe(true)
    expect(html(out)).toContain(`href="${STREAMLIT_URL}"`)
  })

  it('a request slower than 8 seconds is aborted and shows the fallback', async () => {
    vi.useFakeTimers()
    try {
      const fetcher = (_u: string, init?: { signal?: AbortSignal }) =>
        new Promise<Response>((_res, rej) => init?.signal?.addEventListener('abort', () => rej(new DOMException('aborted', 'AbortError'))))
      const p = checkDevice('LLZ', { fetcher, apiBase: BASE, session: memStore(), local: memStore(), now })
      await vi.advanceTimersByTimeAsync(API_TIMEOUT_MS + 1)
      const out = await p
      expect(!out.ok && out.kind === 'network').toBe(true)
      expect(html(out)).toContain(`href="${STREAMLIT_URL}"`)
    } finally {
      vi.useRealTimers()
    }
  })

  it('an unset API base shows the fallback and makes no request', async () => {
    const fetcher = vi.fn(() => json(ANSWER))
    const out = await checkDevice('LLZ', { fetcher, apiBase: null, session: memStore(), local: memStore(), now })
    expect(fetcher).not.toHaveBeenCalled()
    expect(!out.ok && out.kind === 'unconfigured' && out.used === 0).toBe(true)
    const page = html(out)
    expect(page).toContain('not connected to the MaudeSignal API')
    expect(page).toContain(`href="${STREAMLIT_URL}"`)
  })

  it.each([
    ['HTTP 500', () => json({}, 500), 'server'],
    ['not JSON', () => Promise.resolve(new Response('<html>', { status: 200 })), 'bad-response'],
    ['no "check"', () => json({ speakable: 'x' }), 'bad-response'],
    ['another code', () => json({ check: { ...CHECK, product_code: 'QIH' } }), 'bad-response'],
    ['a number missing', () => json({ check: { ...CHECK, current_count: null } }), 'bad-response'],
  ])('%s is a failure, never a faked result', async (_n, f, kind) => {
    const out = await checkDevice('LLZ', { fetcher: f, apiBase: BASE, session: memStore(), local: memStore(), now })
    expect(!out.ok && out.kind === kind).toBe(true)
  })

  it('caches a code for 6 hours (a free repeat), then asks again', async () => {
    const session = memStore()
    const local = memStore()
    const fetcher = vi.fn(() => json(ANSWER))
    const deps = { fetcher, apiBase: BASE, session, local }
    const a = await checkDevice('llz', { ...deps, now })
    expect(a.ok && !a.cached && a.used === 1).toBe(true)
    const b = await checkDevice('LLZ', { ...deps, now: now + 5 * 3600_000 })
    expect(b.ok && b.cached && b.used === 1).toBe(true)
    expect(fetcher).toHaveBeenCalledTimes(1)
    resetLiveCheckMemory() // a new page load: only localStorage remembers
    const b2 = await checkDevice('LLZ', { ...deps, now: now + 5 * 3600_000 })
    expect(b2.ok && b2.cached).toBe(true)
    const c = await checkDevice('LLZ', { ...deps, now: now + 6 * 3600_000 + 1 })
    expect(c.ok && !c.cached).toBe(true)
    expect(fetcher).toHaveBeenCalledTimes(2)
  })

  it('stops after 10 checks in a session, even when storage throws', async () => {
    const boom: KeyStore = {
      getItem: () => {
        throw new Error('blocked')
      },
      setItem: () => {
        throw new Error('blocked')
      },
    }
    const fetcher = vi.fn((u: string) => {
      const code = new URL(u).searchParams.get('product_code')
      return json({ ...ANSWER, check: { ...CHECK, product_code: code } })
    })
    const letters = 'ABCDEFGHIJKL'
    for (let i = 0; i < SESSION_CHECKS; i++) {
      const out = await checkDevice(`A${letters[i]}Z`, { fetcher, apiBase: BASE, session: boom, local: boom, now })
      expect(out.ok).toBe(true)
    }
    expect(checksUsed(boom)).toBe(SESSION_CHECKS)
    const n = fetcher.mock.calls.length
    const out = await checkDevice('QQQ', { fetcher, apiBase: BASE, session: boom, local: boom, now })
    expect(!out.ok && out.kind === 'limit').toBe(true)
    expect(fetcher.mock.calls.length).toBe(n)
  })

  it('rejects a code that is not three letters before any request', async () => {
    const fetcher = vi.fn(() => json(ANSWER))
    const out = await checkDevice('LL1', { fetcher, apiBase: BASE, session: memStore(), local: memStore() })
    expect(out.ok).toBe(false)
    expect(fetcher).not.toHaveBeenCalled()
  })
})
