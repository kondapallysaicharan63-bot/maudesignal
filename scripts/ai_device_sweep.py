r"""Check every product code on FDA's AI-Enabled Medical Device List against openFDA.

HACKATHON-BUILT — Meta Global AI Developer Hackathon (Oct 26 – Nov 4, 2026).

1. Reads FDA's public AI-Enabled Medical Device List (one row per authorized
   device) and collects its product codes.
2. Finds the latest ``date_received`` on openFDA and runs the live check
   (``maudesignal.monitor.live_check``: the detector's four rules on openFDA counts)
   for every code on that same week.
3. Writes ``demo/sweep/ai-device-sweep.json`` and ``docs/hackathon/AI_SWEEP.md``.

No model, no report text, nothing stored but the counts. Runs in GitHub Actions
(``.github/workflows/ai-sweep.yml``); ``OPENFDA_API_KEY`` raises openFDA's daily
limit, and without it the run checks the codes with the most AI devices first and
says how many it covered.

    python scripts/ai_device_sweep.py --out-json demo/sweep/ai-device-sweep.json \
        --out-md docs/hackathon/AI_SWEEP.md
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
from collections import Counter
from datetime import UTC, date, datetime, timedelta
from io import StringIO
from pathlib import Path
from typing import Any

import httpx

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from maudesignal.common.exceptions import OpenFDAAPIError  # noqa: E402
from maudesignal.config import openfda_api_key_from_env  # noqa: E402
from maudesignal.ingestion.openfda_client import (  # noqa: E402
    OPENFDA_EVENT_ENDPOINT,
    OpenFDAClient,
)
from maudesignal.monitor.deterioration import SEVERITY_MIN_REPORTS  # noqa: E402
from maudesignal.monitor.live_check import (  # noqa: E402
    LiveCheck,
    check_product_code,
    count_skipped,
)

AI_LIST_URL = (
    "https://www.fda.gov/medical-devices/artificial-intelligence-enabled-medical-devices/"
    "list-artificial-intelligence-enabled-medical-devices"
)
USER_AGENT = (
    "MaudeSignal/1.0 (open-source research; github.com/kondapallysaicharan63-bot/maudesignal)"
)
#: Codes checked without an openFDA key (about 5 requests each; keyless openFDA allows 1,000/day).
KEYLESS_CODE_CAP = 150
_CODE = re.compile(r"^[A-Z]{3}$")


def ai_list_codes(html_text: str) -> tuple[Counter[str], int]:
    """``(devices per product code, devices on the list)`` from the FDA list page."""
    import pandas as pd

    tables = pd.read_html(StringIO(html_text))
    for t in tables:
        cols = [c for c in t.columns if "product code" in str(c).lower()]
        if cols:
            codes = [str(v).strip().upper() for v in t[cols[0]].dropna()]
            valid = [c for c in codes if _CODE.match(c)]
            return Counter(valid), len(t)
    raise SystemExit(
        "No 'Product Code' column on the FDA list page; tables seen: "
        + "; ".join(", ".join(map(str, t.columns)) for t in tables)
    )


def latest_date(client: httpx.Client, today: date, api_key: str | None) -> date:
    """The latest ``date_received`` on openFDA for any device (one count request)."""
    since = (today - timedelta(days=120)).strftime("%Y%m%d")
    params: dict[str, str] = {
        "search": f"date_received:[{since} TO {today:%Y%m%d}]",
        "count": "date_received",
        "limit": "1000",
    }
    if api_key:
        params["api_key"] = api_key
    r = client.get(OPENFDA_EVENT_ENDPOINT, params=params)
    r.raise_for_status()
    days = [str(x["time"]) for x in r.json()["results"] if int(x["count"]) > 0]
    return datetime.strptime(max(days), "%Y%m%d").date()


def _row(r: LiveCheck, devices: int) -> dict[str, Any]:
    d = r.to_dict()
    d["ai_devices_on_list"] = devices
    return d


def write_markdown(meta: dict[str, Any], rows: list[dict[str, Any]], path: Path) -> None:
    """A short report: totals, then each flagged code with its numbers and query link."""
    flagged = [r for r in rows if r["classification"] != "stable"]
    by_change = Counter(r["change"] for r in flagged)
    w = meta["window"]
    lines = [
        "# AI-enabled device types on openFDA: what changed",
        "",
        f"Generated by `scripts/ai_device_sweep.py` at {meta['generated_utc']} "
        f"(GitHub Actions run {meta.get('run_id') or 'local'}).",
        "",
        f"- FDA AI-Enabled Medical Device List: {meta['devices_on_list']} devices, "
        f"{meta['codes_on_list']} product codes ([source]({AI_LIST_URL})).",
        f"- Checked: {meta['codes_checked']} product codes"
        + (
            f" (the {meta['codes_checked']} with the most AI devices; no openFDA key, "
            "so the keyless daily limit applied)"
            if meta["capped"]
            else ""
        )
        + f"; {meta['errors']} could not be checked.",
        f"- Week compared: {w['current_start']}–{w['current_end']} (the latest week on "
        f"openFDA) vs {w['baseline_start']}–{w['baseline_end']}.",
        f"- Flagged: {len(flagged)} of {len(rows)}"
        + (
            " (" + ", ".join(f"{k}: {v}" for k, v in sorted(by_change.items())) + ")"
            if by_change
            else ""
        )
        + ".",
        "",
        f"Flags need at least {SEVERITY_MIN_REPORTS} reports this week; "
        f"{count_skipped(rows)} code(s) skipped for too few reports.",
        "",
        "Same four rules as the app (7 days vs the 4 weeks before; counts only). A triage",
        "signal for a person to review, not a finding about any device or company.",
        "",
    ]
    if flagged:
        lines += [
            "| Product code | AI devices on list | Change | This week | Weekly mean before |"
            " Injury/death this week | openFDA query |",
            "|---|---|---|---|---|---|---|",
        ]
        for r in sorted(flagged, key=lambda r: (-r["current_count"], r["product_code"])):
            url = r["queries"][1][1] if len(r["queries"]) > 1 else r["queries"][0][1]
            lines.append(
                f"| {r['product_code']} | {r['ai_devices_on_list']} | {r['change']} | "
                f"{r['current_count']} | {r['baseline_weekly_mean']:.2f} | "
                f"{r['current_severe_count']} | [open]({url}) |"
            )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    """Run the sweep and write the JSON and Markdown outputs."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-json", type=Path, default=ROOT / "demo/sweep/ai-device-sweep.json")
    ap.add_argument("--out-md", type=Path, default=ROOT / "docs/hackathon/AI_SWEEP.md")
    ap.add_argument("--run-id", default="")
    args = ap.parse_args()

    key = openfda_api_key_from_env()
    today = datetime.now(UTC).date()
    with httpx.Client(timeout=60, headers={"User-Agent": USER_AGENT}) as web:
        page = web.get(AI_LIST_URL, follow_redirects=True)
        page.raise_for_status()
        per_code, n_devices = ai_list_codes(page.text)
        as_of = latest_date(web, today, key)
    print(f"[sweep] list: {n_devices} devices, {len(per_code)} codes; as of {as_of}")

    order = [c for c, _ in per_code.most_common()]
    capped = key is None and len(order) > KEYLESS_CODE_CAP
    order = order[:KEYLESS_CODE_CAP] if capped else order
    rows: list[dict[str, Any]] = []
    errors: dict[str, str] = {}
    with OpenFDAClient(api_key=key) as client:
        for i, code in enumerate(order, 1):
            try:
                r = check_product_code(client, code, today, as_of=as_of)
                rows.append(_row(r, per_code[code]))
            except OpenFDAAPIError as exc:
                errors[code] = str(exc)
            if i % 25 == 0:
                print(f"[sweep] {i}/{len(order)} checked", flush=True)
            time.sleep(0.3)

    window = rows[0]["window"] if rows else {}
    meta = {
        "generated_utc": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "run_id": args.run_id,
        "source": AI_LIST_URL,
        "devices_on_list": n_devices,
        "codes_on_list": len(per_code),
        "codes_checked": len(order),
        "capped": capped,
        "errors": len(errors),
        "as_of": as_of.strftime("%Y%m%d"),
        "window": {k: f"{v[:4]}-{v[4:6]}-{v[6:]}" for k, v in window.items()},
    }
    args.out_json.parent.mkdir(parents=True, exist_ok=True)
    args.out_json.write_text(
        json.dumps({"meta": meta, "rows": rows, "errors": errors}, indent=1) + "\n",
        encoding="utf-8",
    )
    write_markdown(meta, rows, args.out_md)
    flagged = sum(r["classification"] != "stable" for r in rows)
    print(f"[sweep] {flagged} of {len(rows)} flagged; {len(errors)} errors → {args.out_md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
