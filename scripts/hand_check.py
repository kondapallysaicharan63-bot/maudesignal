"""Build the hand-check worksheet for the recorded copilot answers.

HACKATHON-BUILT — Meta Global AI Developer Hackathon (Oct 26 – Nov 4, 2026).

Reads every transcript in ``demo/transcripts`` and the demo database and writes
``docs/hackathon/HAND_CHECK.md``:

* gate pass rates per answer (first pass and after the repair turn), and the
  totals, computed from the transcripts — nothing is typed in by hand;
* every final sentence with its gate status and cited evidence, each id looked
  up in the stored records (MAUDE report, 510(k), recall, PubMed) so a reviewer
  can open it;
* a ``Hand verdict`` column per sentence, left ``pending`` until a person has
  checked the sentence against the cited record. Verdicts already filled in a
  previous worksheet are kept when the same sentence appears again.

    python scripts/hand_check.py
"""

from __future__ import annotations

import argparse
import re
import sqlite3
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from maudesignal.copilot.transcript import load_transcripts  # noqa: E402

VERDICT_RE = re.compile(r"^\| (?P<key>[0-9a-z-]+#\d+) \|.*\| (?P<verdict>[^|]+) \|$")


def _lookup(db: Path) -> dict[str, str]:
    """``evidence id -> what it is`` for every stored record."""
    con = sqlite3.connect(db)
    try:
        out = {
            rid: f"MAUDE report ({pc})"
            for rid, pc in con.execute(
                "select maude_report_id, product_code from normalized_events"
            )
        }
        names = {"fda_510k": "510(k)", "fda_recall": "recall", "pubmed": "PubMed"}
        for st, sid in con.execute("select source_type, source_id from external_sources"):
            out.setdefault(sid, names.get(st, st))
    finally:
        con.close()
    return out


def _rate(passed: int, blocked: int) -> str:
    total = passed + blocked
    return f"{passed}/{total} ({100 * passed / total:.1f}%)" if total else "0/0 (n/a)"


def _old_verdicts(path: Path) -> dict[str, str]:
    if not path.is_file():
        return {}
    found = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        m = VERDICT_RE.match(line)
        if m and m["verdict"].strip() != "pending":
            found[m["key"]] = m["verdict"].strip()
    return found


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def build(transcripts: list[dict[str, Any]], known: dict[str, str], old: dict[str, str]) -> str:
    """Render the worksheet Markdown."""
    lines = [
        "# Hand-check of recorded copilot answers",
        "",
        "Generated by `scripts/hand_check.py` from `demo/transcripts/` and the demo database. "
        "Gate numbers come from the recorded runs; a `Hand verdict` other than `pending` "
        "was entered by a person after opening the cited record.",
        "",
    ]
    if not transcripts:
        lines += ["No recorded transcripts yet — run the *Record live Meta runs* workflow.", ""]
        return "\n".join(lines)

    fp_p = sum(t["first_pass"]["passed"] for t in transcripts)
    fp_b = sum(t["first_pass"]["blocked"] for t in transcripts)
    fn_p = sum(t["final"]["passed"] for t in transcripts)
    fn_b = sum(t["final"]["blocked"] for t in transcripts)
    clean_first = sum(1 for t in transcripts if t["first_pass"]["blocked"] == 0)
    clean_final = sum(1 for t in transcripts if t["final"]["blocked"] == 0)
    repaired = sum(1 for t in transcripts if t.get("repaired"))
    cost = sum(float(t.get("usage", {}).get("cost_usd") or 0.0) for t in transcripts)
    models = sorted({str(t.get("model")) for t in transcripts})
    lines += [
        "## Gate pass rates",
        "",
        f"- Answers: {len(transcripts)} (model: {', '.join(models)})",
        f"- Sentences passing the gate, first pass: {_rate(fp_p, fp_b)}",
        f"- Sentences passing the gate, final (after at most one repair turn): "
        f"{_rate(fn_p, fn_b)}",
        f"- Answers with nothing blocked, first pass: {clean_first}/{len(transcripts)}; "
        f"final: {clean_final}/{len(transcripts)}",
        f"- Answers that used the repair turn: {repaired}",
        f"- Recorded model cost: ${cost:.4f}",
        "",
        "| Answer | Recorded (UTC) | Tools | First pass | Final | Repaired |",
        "|---|---|---|---|---|---|",
    ]
    for t in transcripts:
        tools = ", ".join(c["name"] for c in t.get("tool_calls", [])) or "—"
        lines.append(
            f"| {t['label']} | {t.get('recorded_at_utc', '')} | {tools} | "
            f"{_rate(t['first_pass']['passed'], t['first_pass']['blocked'])} | "
            f"{_rate(t['final']['passed'], t['final']['blocked'])} | "
            f"{'yes' if t.get('repaired') else 'no'} |"
        )
    lines.append("")

    verdicts = {"pending": 0}
    for t in transcripts:
        lines += [f"## {t['label']}", "", f"**Q:** {_cell(t['question'])}", ""]
        if t.get("voice"):
            lines += [
                f"*Heard (Voice Transcribe):* {_cell(t['voice'].get('transcript_text', ''))}",
                "",
            ]
        lines += [
            "| # | Sentence | Gate | Cited evidence | Hand verdict |",
            "|---|---|---|---|---|",
        ]
        for i, s in enumerate(t["final"]["sentences"], start=1):
            ids = sorted({e for c in s.get("claims", []) for e in c.get("evidence_ids", [])})
            cited = "; ".join(f"{e} ({known.get(e, 'not a stored record')})" for e in ids)
            key = f"{t['label']}#{i}"
            verdict = old.get(key, "pending")
            verdicts[verdict.split()[0]] = verdicts.get(verdict.split()[0], 0) + 1
            reasons = f" — {_cell('; '.join(s.get('reasons', [])))}" if s.get("reasons") else ""
            lines.append(
                f"| {key} | {_cell(s['text'])} | {s['status']}{reasons} | {cited or '—'} | "
                f"{verdict} |"
            )
        lines.append("")
    tally = ", ".join(f"{k} {v}" for k, v in sorted(verdicts.items()) if v)
    lines += ["## Hand verdict tally", "", tally, ""]
    return "\n".join(lines)


def main() -> int:
    """Write the worksheet; returns a process exit code."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--transcripts", type=Path, default=ROOT / "demo/transcripts")
    ap.add_argument("--db", type=Path, default=ROOT / "data/demo/maudesignal_demo.db")
    ap.add_argument("--out", type=Path, default=ROOT / "docs/hackathon/HAND_CHECK.md")
    args = ap.parse_args()
    md = build(load_transcripts(args.transcripts), _lookup(args.db), _old_verdicts(args.out))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(md, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
