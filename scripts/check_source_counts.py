"""F12 acceptance check: stored report-source counts vs openFDA's own counts.

HACKATHON-BUILT — Meta Global AI Developer Hackathon (Oct 26 – Nov 4, 2026).

For each product code in the demo database, asks openFDA
``count=report_source_code.exact`` over exactly the stored ``date_received``
window and compares it with the counts MaudeSignal computes from its stored
records. Also records openFDA's all-time counts for each code (the numbers a
pitch would quote). Keyless openFDA is enough (``OPENFDA_API_KEY`` is used when
set). Writes ``docs/hackathon/SOURCE_COUNTS.md``; exit code 1 on any mismatch.

    python scripts/check_source_counts.py
"""

from __future__ import annotations

import argparse
import os
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import httpx

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from maudesignal.gate.evidence import normalize_source  # noqa: E402
from maudesignal.ingestion.openfda_client import (  # noqa: E402
    OPENFDA_EVENT_ENDPOINT,
    search_param,
)
from maudesignal.monitor.sources import source_counts, sourced_reports  # noqa: E402
from maudesignal.storage.database import Database  # noqa: E402


def openfda_counts(query: str, api_key: str | None) -> dict[str, int]:
    """``normalized source -> count`` for an openFDA device-event search."""
    params: dict[str, Any] = {"search": search_param(query), "count": "report_source_code.exact"}
    if api_key:
        params["api_key"] = api_key
    resp = httpx.get(OPENFDA_EVENT_ENDPOINT, params=params, timeout=30.0)
    if resp.status_code == 404:
        return {}
    resp.raise_for_status()
    out: dict[str, int] = {}
    for row in resp.json().get("results", []):
        key = normalize_source(str(row.get("term"))) or f"other: {row.get('term')}"
        out[key] = out.get(key, 0) + int(row.get("count", 0))
    return dict(sorted(out.items()))


def _fmt(counts: dict[str, int]) -> str:
    return ", ".join(f"{k} {v}" for k, v in counts.items()) or "none"


def main() -> int:
    """Run the comparison; returns a process exit code."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", type=Path, default=ROOT / "data/demo/maudesignal_demo.db")
    ap.add_argument("--out", type=Path, default=ROOT / "docs/hackathon/SOURCE_COUNTS.md")
    args = ap.parse_args()
    key = os.environ.get("OPENFDA_API_KEY") or None

    reports = sourced_reports(Database(args.db))
    stored = source_counts(reports)
    lines = [
        "# Report sources: stored records vs openFDA",
        "",
        f"Generated by `scripts/check_source_counts.py` at "
        f"{datetime.now(UTC).isoformat(timespec='seconds')} against "
        "`https://api.fda.gov/device/event.json` (`count=report_source_code.exact`).",
        "",
        "## Stored window: do MaudeSignal's counts match openFDA?",
        "",
        "| Product code | Stored window (date_received) | MaudeSignal (stored) | openFDA | Match |",
        "|---|---|---|---|---|",
    ]
    mismatches = 0
    all_time: dict[str, dict[str, int]] = {}
    for pc in sorted(stored):
        days = sorted(r.date_received for r in reports if r.product_code == pc and r.date_received)
        lo, hi = days[0], days[-1]
        base = f"device.device_report_product_code:{pc}"
        live = openfda_counts(f"{base}+AND+date_received:[{lo}+TO+{hi}]", key)
        ours = {k: v for k, v in stored[pc].items() if k != "unknown"}
        ok = ours == live
        mismatches += 0 if ok else 1
        lines.append(
            f"| {pc} | {lo}–{hi} | {_fmt(stored[pc])} | {_fmt(live)} | "
            f"{'yes' if ok else '**no**'} |"
        )
        all_time[pc] = openfda_counts(base, key)
    lines += [
        "",
        "A mismatch can be real (openFDA re-publishes weekly; reports skipped at seed time for a "
        "missing narrative are not stored) and is listed, not hidden.",
        "",
        "## openFDA, all dates (what a pitch may quote)",
        "",
        "| Product code | Total | By source | Filed by a manufacturer |",
        "|---|---|---|---|",
    ]
    for pc, counts in all_time.items():
        total = sum(counts.values())
        mfr = counts.get("manufacturer", 0)
        share = f"{100 * mfr / total:.1f}%" if total else "n/a"
        lines.append(f"| {pc} | {total:,} | {_fmt(counts)} | {mfr:,} ({share}) |")
    lines.append("")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.out}; mismatches: {mismatches}")
    return 1 if mismatches else 0


if __name__ == "__main__":
    raise SystemExit(main())
